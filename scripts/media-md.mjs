// Writes MEDIA.md: every file under public/ that the site ships, with its source and byte size.  node scripts/media-md.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]))
const files = walk('public').sort()
// hero frame index → source clip (scripts/hero-frames.sh SHOTS)
const heroSrc = (i) => (i <= 40 ? 'cg-depart-1' : i <= 80 ? 'cg-depart-2' : i <= 120 ? 'cg-depart-3' : 'cg-port')
const source = (f) => {
  let m
  if ((m = f.match(/^public\/hero\/([dm])_(\d+)\.webp$/))) return `${heroSrc(+m[2])} master (${m[1] === 'd' ? 'master.mp4 → 1280×720' : 'phone.mp4 → 540×960'})`
  if ((m = f.match(/^public\/media\/((?:cg|hf)-[a-z0-9-]+)_(\d+)\.(avif|webp)$/))) return `${m[1]} poster (source public/media, ${m[2]}w)`
  if ((m = f.match(/^public\/media\/(prod-[a-z-]+)_(\d+)/))) return `${m[1]} product still (source public/media)`
  if (f.startsWith('public/textures/')) return 'globe albedo (source public/textures)'
  if (f.startsWith('public/fonts/')) return 'font (source public/fonts, OFL)'
  if (f.endsWith('.pdf')) return 'company profile (source public/docs)'
  return 'site file (source public/ or new)'
}
let total = 0
const rows = files.map((f) => {
  const b = statSync(f).size
  total += b
  return `| \`${f.replace(/^public/, '')}\` | ${source(f)} | ${b.toLocaleString('en')} |`
})
const by = (re) => files.filter((f) => re.test(f)).reduce((s, f) => s + statSync(f).size, 0)
const mb = (b) => (b / 1e6).toFixed(2) + ' MB'
writeFileSync(
  'MEDIA.md',
  `# MEDIA

Every file the site ships from \`public/\` (generated by \`node scripts/media-md.mjs\`). Sources are paths in
skylark-exim-v3; nothing here is newly generated media. Masters and every unused tier stay in the source repo.

| Group | Files | Size |
|---|---|---|
| Hero sequence, desktop (\`/hero/d_*\`) | ${files.filter((f) => /hero\/d_/.test(f)).length} | ${mb(by(/hero\/d_/))} |
| Hero sequence, phone (\`/hero/m_*\`) | ${files.filter((f) => /hero\/m_/.test(f)).length} | ${mb(by(/hero\/m_/))} |
| Chain stills (\`/media/cg-*\`, \`/media/hf-*\`) | ${files.filter((f) => /media\/(cg|hf)-/.test(f)).length} | ${mb(by(/media\/(cg|hf)-/))} |
| Product stills (\`/media/prod-*\`) | ${files.filter((f) => /media\/prod-/.test(f)).length} | ${mb(by(/media\/prod-/))} |
| Everything else (fonts, texture, PDF, icons, pages) | ${files.filter((f) => !/hero\/|media\//.test(f)).length} | ${mb(by(/^(?!public\/(hero|media)\/)/))} |
| **Total** | **${files.length}** | **${mb(total)}** |

Old site for comparison: 2,393 files under \`public/media\` alone (1.2 GB in the wt-story worktree).

| File | Source | Bytes |
|---|---|---|
${rows.join('\n')}
`,
)
console.log(files.length, 'files', mb(total))
